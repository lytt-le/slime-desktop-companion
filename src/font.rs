fn glyph(c: char) -> &'static (u8, [u8; 8]) {
    let i = c as usize;
    &GLYPHS[if (32..127).contains(&i) { i - 32 } else { '?' as usize - 32 }]
}

/// How far `c` moves the pen, gap included.
pub fn advance(c: char) -> usize {
    glyph(c).0 as usize
}

/// Width of `s` in pixels (without the gap after its last character).
pub fn text_width(s: &str) -> usize {
    s.chars().map(advance).sum::<usize>().saturating_sub(1)
}

/// Maps common non-ASCII punctuation to ASCII; anything else unprintable becomes '?'.
pub fn to_ascii(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        let mapped = match c {
            '\u{2018}' | '\u{2019}' | '\u{2032}' => '\'',
            '\u{201C}' | '\u{201D}' | '\u{2033}' => '"',
            '\u{2013}' | '\u{2014}' | '\u{2212}' => '-',
            '\u{2026}' => {
                out.push_str("...");
                continue;
            }
            '\u{00A0}' | '\t' | '\n' | '\r' => ' ',
            '\u{00D7}' => 'x',
            '\u{00B0}' => 'o',
            c if (' '..='~').contains(&c) => c,
            _ => '?',
        };
        out.push(mapped);
    }
    out
}

/// Whether pixel (col, row) of `c`'s glyph is set.
pub fn pixel(c: char, col: usize, row: usize) -> bool {
    row < GLYPH_H && col < 8 && glyph(c).1[row] >> col & 1 == 1
}

/// Greedy word wrap to lines no wider than `cols` layout columns (`cols * ADVANCE`
/// pixels; proportional text fits more characters than that).
pub fn wrap(text: &str, cols: usize) -> Vec<String> {
    let max = (cols * ADVANCE).saturating_sub(1).max(ADVANCE);
    let mut lines = Vec::new();
    let mut line = String::new();
    for word in text.split_whitespace() {
        let mut word = word.to_string();
        // Words longer than a line are split.
        while text_width(&word) > max {
            if !line.is_empty() {
                lines.push(std::mem::take(&mut line));
            }
            let mut cut = 0;
            let mut w = 0;
            for (i, c) in word.char_indices() {
                if w + advance(c) - 1 > max && i > 0 {
                    break;
                }
                w += advance(c);
                cut = i + c.len_utf8();
            }
            let rest = word.split_off(cut);
            lines.push(word);
            word = rest;
        }
        if line.is_empty() {
            line = word;
        } else if text_width(&line) + advance(' ') + 1 + text_width(&word) <= max {
            line.push(' ');
            line.push_str(&word);
        } else {
            lines.push(std::mem::replace(&mut line, word));
        }
    }
    if !line.is_empty() {
        lines.push(line);
    }
    lines
}
